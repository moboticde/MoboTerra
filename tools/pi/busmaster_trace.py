"""BUSMASTER CAN ASCII layout, with disk-backed chronological finalization.

Layout reference: rbei-etas/busmaster, FrameProcessor/LogObjectCAN.cpp.
ROS Tx rows describe publications, not independently confirmed transmissions.
"""
import datetime
import os
from pathlib import Path
import subprocess
import threading
import time


def clock_text(stamp_ns):
    seconds, nanoseconds = divmod(int(stamp_ns), 1_000_000_000)
    return datetime.datetime.fromtimestamp(seconds).strftime('%H:%M:%S') + f':{nanoseconds // 100_000:04d}'


def date_text(stamp_ns):
    seconds, nanoseconds = divmod(int(stamp_ns), 1_000_000_000)
    date = datetime.datetime.fromtimestamp(seconds)
    return f'{date.day}:{date.month}:{date.year} {date.hour}:{date.minute}:{date.second}:{nanoseconds // 1_000_000}'


class BusmasterTrace:
    def __init__(self, path, started_ns, interface='can0', bitrate=500000, *, tx_origin=None):
        self.path = Path(path)
        self.started_ns = started_ns
        self.lock = threading.Lock()
        self.frames = self.notes = 0
        self.closed = False
        self.journal_path = self.path.with_name('.' + self.path.name + '.frames')
        self.live = self.path.open('x', buffering=1)
        try:
            self.journal = self.journal_path.open('x', buffering=1)
        except BaseException:
            self.live.close()
            self.path.unlink()
            raise
        zone = datetime.datetime.fromtimestamp(started_ns // 1_000_000_000).astimezone().strftime('%Z %z')
        self.header = '\n'.join([
            '***BUSMASTER Ver 3.0.0***',
            '***PROTOCOL CAN***',
            '***NOTE: Generated by MoboTerra recorder using BUSMASTER CAN ASCII layout***',
            '***[START LOGGING SESSION]***',
            f'***START DATE AND TIME {date_text(started_ns)}***',
            '***HEX***',
            '***SYSTEM MODE***',
            f'***NOTE: Local timezone {zone}; timestamp resolution 0.1 ms***',
            '***NOTE: ' + (tx_origin or 'Tx includes ROS source publications before the sender; wire transmission is not independently confirmed') + '***',
            '***NOTE: Rx is raw socket reception; local socket echoes, when identified, are Tx***',
            '***NOTE: Live rows follow arrival order; file is sorted by source/acquisition timestamp when stopped***',
            '***START CHANNEL BAUD RATE***',
            f'***CHANNEL 1 - SocketCAN {interface} - {bitrate} bps***',
            '***END CHANNEL BAUD RATE***',
            '***<Time><Tx/Rx><Channel><CAN ID><Type><DLC><DataBytes>***',
        ]) + '\n'
        self.live.write(self.header)

    def _append(self, stamp_ns, line):
        with self.lock:
            if self.closed:
                raise RuntimeError('Trace is already closed')
            self.journal.write(f'{int(stamp_ns)}\t{line}\n')
            self.live.write(line + '\n')

    def note(self, stamp_ns, text):
        clean = str(text).replace('\r', ' ').replace('\n', ' ').replace('\t', ' ').replace('***', '')
        self._append(stamp_ns, f'***NOTE: {clock_text(stamp_ns)} {clean}***')
        self.notes += 1

    def frame(self, stamp_ns, direction, identifier, dlc, data, *, extended=False, rtr=False, error=False):
        if direction not in ('Rx', 'Tx') or not 0 <= dlc <= 8:
            raise ValueError('Expected Rx/Tx and classical CAN DLC 0..8')
        payload = bytes(data)
        if error:
            self.note(stamp_ns, f'LINUX_CAN_ERROR direction={direction} raw_id=0x{identifier:08X} '
                f'dlc={dlc} data={payload[:dlc].hex(" ").upper()}')
            return
        if not 0 <= identifier <= (0x1fffffff if extended else 0x7ff):
            raise ValueError('Invalid CAN identifier')
        if not rtr and len(payload) < dlc:
            raise ValueError('Payload shorter than DLC')
        label = f'0x{identifier:08X}' if extended else f'0x{identifier:03X}'
        kind = ('x' if extended else 's') + ('r' if rtr else '')
        body = '' if rtr else ' ' + payload[:dlc].hex(' ').upper() if dlc else ''
        self._append(stamp_ns, f'{clock_text(stamp_ns)} {direction} 1 {label} {kind} {dlc}{body}')
        self.frames += 1

    def close(self, finished_ns=None):
        finished_ns = time.time_ns() if finished_ns is None else finished_ns
        with self.lock:
            if self.closed:
                return
            self.closed = True
            self.journal.close()
            self.live.close()
        sorted_path = self.path.with_name('.' + self.path.name + '.sorted')
        completed_path = self.path.with_name('.' + self.path.name + '.complete')
        try:
            subprocess.run(['sort', '--stable', '--numeric-sort', '--key=1,1',
                '--field-separator=\t', '--output=' + str(sorted_path), str(self.journal_path)],
                env=dict(os.environ, LC_ALL='C'), check=True)
            with completed_path.open('x') as output, sorted_path.open() as ordered:
                output.write(self.header)
                for row in ordered:
                    output.write(row.split('\t', 1)[1])
                output.write(f'***END DATE AND TIME {date_text(finished_ns)}***\n')
                output.write('***[STOP LOGGING SESSION]***\n')
            os.replace(completed_path, self.path)
            self.journal_path.unlink()
        finally:
            sorted_path.unlink(missing_ok=True)
            completed_path.unlink(missing_ok=True)
